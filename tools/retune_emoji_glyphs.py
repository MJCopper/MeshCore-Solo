#!/usr/bin/env python3
"""Retune generated OpenMoji bitmaps for recognisability at 5x8 pixels.

At this geometry category silhouettes are more useful than damaged detail.
The carefully drawn runtime overrides remain authoritative and are not stored
here; this pass makes the complete generated fallback set visually coherent.
"""

import argparse
import re
from pathlib import Path


FACE = [0x0E, 0x11, 0x15, 0x11, 0x11, 0x0A, 0x04, 0x00]
FACE_OPEN = [0x0E, 0x11, 0x15, 0x11, 0x0A, 0x11, 0x0E, 0x00]
FACE_LOVE = [0x0E, 0x11, 0x1B, 0x11, 0x15, 0x0A, 0x04, 0x00]
FACE_COOL = [0x0E, 0x11, 0x1F, 0x11, 0x11, 0x0A, 0x04, 0x00]
FACE_SAD = [0x0E, 0x11, 0x15, 0x11, 0x04, 0x0A, 0x11, 0x00]
FACE_CRY = [0x0E, 0x11, 0x15, 0x12, 0x04, 0x0A, 0x11, 0x00]
FACE_ANGRY = [0x0E, 0x11, 0x0A, 0x11, 0x04, 0x0A, 0x11, 0x00]
FACE_SHOCK = [0x0E, 0x11, 0x15, 0x11, 0x04, 0x0A, 0x04, 0x00]
FACE_SLEEP = [0x0E, 0x11, 0x0A, 0x11, 0x00, 0x0E, 0x00, 0x00]
PERSON = [0x04, 0x0E, 0x04, 0x0E, 0x15, 0x04, 0x0A, 0x11]
HAND = [0x04, 0x06, 0x04, 0x0C, 0x1F, 0x1E, 0x0C, 0x00]
ANIMAL = [0x0A, 0x1F, 0x15, 0x11, 0x15, 0x0E, 0x04, 0x00]
FOOD = [0x04, 0x0E, 0x1F, 0x1F, 0x1F, 0x0E, 0x04, 0x00]
WEATHER = [0x04, 0x15, 0x0E, 0x1F, 0x0E, 0x0A, 0x0A, 0x00]
VEHICLE = [0x00, 0x00, 0x0E, 0x1F, 0x15, 0x1F, 0x0A, 0x00]
BALL = [0x04, 0x0E, 0x15, 0x1B, 0x15, 0x0E, 0x04, 0x00]
OBJECT = [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x0E, 0x00]
HEART = [0x00, 0x0A, 0x1F, 0x1F, 0x0E, 0x04, 0x00, 0x00]
BROKEN_HEART = [0x00, 0x0A, 0x1B, 0x16, 0x0C, 0x04, 0x00, 0x00]
EYES = [0x00, 0x0A, 0x15, 0x11, 0x15, 0x0A, 0x00, 0x00]
FIRE = [0x04, 0x06, 0x0E, 0x0F, 0x1F, 0x0E, 0x04, 0x00]
POOP = [0x04, 0x0E, 0x04, 0x0E, 0x15, 0x11, 0x0E, 0x00]
GIFT = [0x0A, 0x1F, 0x04, 0x1F, 0x15, 0x15, 0x1F, 0x00]
PARTY = [0x01, 0x02, 0x14, 0x0C, 0x1E, 0x0F, 0x07, 0x00]


def retune_bitmap(codepoint, original):
    """Return a category-readable glyph, preserving good standalone symbols."""
    cp = codepoint
    if cp in (0x2764, 0x1F495, 0x1F496, 0x1F499, 0x1F49A, 0x1F49B,
              0x1F49C, 0x1F5A4, 0x1F9E1):
        return HEART
    if cp == 0x1F494:
        return BROKEN_HEART
    if cp == 0x1F440:
        return EYES
    if cp == 0x1F525:
        return FIRE
    if cp == 0x1F4A9:
        return POOP
    if cp in (0x1F381,):
        return GIFT
    if cp in (0x1F389, 0x1F973):
        return PARTY
    if cp in (0x1F60D, 0x1F618):
        return FACE_LOVE
    if cp in (0x1F60E,):
        return FACE_COOL
    if cp in (0x1F622, 0x1F625, 0x1F62D):
        return FACE_CRY
    if cp in (0x1F614, 0x1F61E, 0x1F641, 0x1F97A):
        return FACE_SAD
    if cp in (0x1F620, 0x1F621, 0x1F624, 0x1F92C):
        return FACE_ANGRY
    if cp in (0x1F62E, 0x1F631, 0x1F632, 0x1F633, 0x1F92F):
        return FACE_SHOCK
    if cp in (0x1F62A, 0x1F634):
        return FACE_SLEEP
    if 0x1F600 <= cp <= 0x1F64F or 0x1F910 <= cp <= 0x1F92F \
            or 0x1F970 <= cp <= 0x1F97F or 0x1FAE0 <= cp <= 0x1FAEF:
        return FACE_OPEN if cp & 1 else FACE
    if 0x1F446 <= cp <= 0x1F450 or 0x1F590 <= cp <= 0x1F596 \
            or 0x1F918 <= cp <= 0x1F91F:
        return HAND
    if 0x1F466 <= cp <= 0x1F487 or 0x1F9D0 <= cp <= 0x1F9DD:
        return PERSON
    if 0x1F400 <= cp <= 0x1F43F or 0x1F980 <= cp <= 0x1F9AE:
        return ANIMAL
    if 0x1F345 <= cp <= 0x1F37F:
        return FOOD
    if 0x1F300 <= cp <= 0x1F320 or cp in (0x2600, 0x2601, 0x26C8, 0x2744):
        return WEATHER
    if 0x1F680 <= cp <= 0x1F6FF:
        return VEHICLE
    if 0x1F3A0 <= cp <= 0x1F3FF:
        return BALL
    if 0x1F4BB <= cp <= 0x1F4FF or 0x1F500 <= cp <= 0x1F5FF:
        return OBJECT
    return original


def retune_header(path):
    text = path.read_text()
    codepoint_block = text[text.index("emojiGlyphCodepoints"):text.index("emojiGlyphRows")]
    codepoints = [int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]{4,6})", codepoint_block)]
    row_pattern = re.compile(r"^(\s*)\{ ((?:0x[0-9A-Fa-f]{2},? ?){8}) \}, // U\+([0-9A-Fa-f]+)$", re.MULTILINE)
    seen = 0

    def replace(match):
        nonlocal seen
        cp = int(match.group(3), 16)
        if seen >= len(codepoints) or codepoints[seen] != cp:
            raise ValueError(f"glyph/codepoint order mismatch at U+{cp:04X}")
        original = [int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]{2})", match.group(2))]
        rows = retune_bitmap(cp, original)
        seen += 1
        return match.group(1) + "{ " + ", ".join(f"0x{row:02X}" for row in rows) + f" }}, // U+{cp:04X}"

    updated = row_pattern.sub(replace, text)
    if seen != len(codepoints):
        raise ValueError(f"expected {len(codepoints)} scalar glyphs, retuned {seen}")
    path.write_text(updated)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    retune_header(args.header)


if __name__ == "__main__":
    main()
